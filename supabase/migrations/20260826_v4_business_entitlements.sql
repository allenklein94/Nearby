-- already-live brand_partners.tier column. No Stripe, no real money --
-- this is purely "what does each tier's real feature set unlock,"
-- config-driven rather than hardcoded, matching this file's own locked
-- "client-side hiding is not security" rule.
--
-- brand_partners.tier is the one canonical plan column -- already real,
-- already `check (tier in ('basic','growth','brand'))`, already
